-- Création de la table access_token dans Supabase avec les bonnes relations
create table if not exists public.access_token (
  access_token_id bigint primary key generated by default as identity,
  user_id bigint references public.utilisateurs(id) on delete cascade,
  access_token text,
  ip_address varchar(15),
  date_maj timestamptz default now(),
  created_at timestamptz default now()
);

-- Ajout des policies pour RLS (Row Level Security)
alter table public.access_token enable row level security;

create policy "Enable read access for authenticated users" on public.access_token
  for select
  to authenticated
  using (auth.uid() = user_id);

create policy "Enable insert access for authenticated users" on public.access_token
  for insert
  to authenticated
  with check (auth.uid() = user_id);

-- Index pour améliorer les performances
create index if not exists access_token_user_id_idx on public.access_token(user_id);