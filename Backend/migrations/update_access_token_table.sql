-- Mise à jour de la table access_token pour correspondre à la structure utilisée
drop table if exists public.access_token;

create table public.access_token (
    id bigint primary key generated by default as identity,
    user_id bigint references public.utilisateurs(id) on delete cascade,
    token text not null,
    created_at timestamptz default now(),
    expires_at timestamptz not null,
    ip_address varchar(45)
);

-- Indexes
create index access_token_user_id_idx on public.access_token(user_id);
create index access_token_token_idx on public.access_token(token);

-- RLS Policies
alter table public.access_token enable row level security;

create policy "Users can read their own tokens"
    on public.access_token for select
    using (auth.uid()::text = user_id::text);

create policy "Users can insert their own tokens"
    on public.access_token for insert
    with check (auth.uid()::text = user_id::text);

create policy "Users can delete their own tokens"
    on public.access_token for delete
    using (auth.uid()::text = user_id::text);